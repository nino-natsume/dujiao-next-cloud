#!/bin/sh
# =============================================================================
# 入口脚本：redis 后台跑，dujiao 前台跑
# dujiao 保持前台 -> 它的日志直接进容器 stdout -> Render 控制台可见
# =============================================================================
set -e

# 启动 Redis（仅本机回环；重启丢数据没关系）
redis-server --bind 127.0.0.1 --port 6379 --appendonly no &

# 前台启动主程序；dujiao 崩溃 = 容器退出 = Render 自动重启实例
exec /app/dujiao-next